"""Build results/runs.md, results/results.csv, results/seeded.csv and results/stage_pass_rates.csv.

Everything is read from GitHub (the Actions runs, the pull requests) and from the `autose-runs` branch,
which holds the artifacts of every run. Nothing is typed in by hand except the notes in
results/run_notes.csv. Hidden-test scores come from experiment/score.py and are cached in
results/score_cache.json (they need the private hidden tests; use --no-score to skip).

    python experiment/collect.py            # write all files
    python experiment/collect.py --no-score # skip hidden-test scoring
"""
import argparse
import csv
import json
import os
import re
import subprocess
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

REPO = "Ekansh0301/tinydb"
ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
HIDDEN_NO = {4: 1, 5: 2, 6: 3, 7: 4, 8: 5}          # GitHub issue number -> hidden test number (I1..I5)
LABELS = ROOT / "experiment" / "seeded_prs" / "labels.csv"


def sh(args, cwd=None, check=True):
    p = subprocess.run(args, cwd=cwd, capture_output=True, text=True)
    if check and p.returncode:
        raise RuntimeError("%s: %s" % (" ".join(args[:3]), p.stderr[-300:]))
    return p.stdout


def gh_json(path):
    out = sh(["gh", "api", "--paginate", path, "--jq", ".workflow_runs[]|@json"] if "actions/runs" in path else ["gh", "api", path])
    return [json.loads(l) for l in out.splitlines() if l.strip()] if "actions/runs" in path else json.loads(out)


def load_runs():
    rows = gh_json("repos/%s/actions/runs?per_page=100" % REPO)
    return sorted(rows, key=lambda r: r["created_at"])


def clone_runs_branch():
    d = Path(tempfile.mkdtemp(prefix="runs-"))
    sh(["git", "clone", "-q", "--branch", "autose-runs", "--single-branch", "https://github.com/%s.git" % REPO, str(d)])
    return d


def read_json(p, default=None):
    try:
        return json.loads(Path(p).read_text())
    except (OSError, ValueError):
        return default


def read_lines(p):
    try:
        return [json.loads(l) for l in Path(p).read_text().splitlines() if l.strip()]
    except (OSError, ValueError):
        return []


def minutes(a, b):
    from datetime import datetime
    f = "%Y-%m-%dT%H:%M:%SZ"
    return round((datetime.strptime(b, f) - datetime.strptime(a, f)).total_seconds() / 60, 1)


# ---- notes ----------------------------------------------------------------------------------
def load_notes():
    f = RESULTS / "run_notes.csv"
    if not f.exists():
        return {}
    return {r["run_id"]: r["note"] for r in csv.DictReader(f.open())}


# ---- runs.md ---------------------------------------------------------------------------------
def write_runs_md(runs, notes, prs):
    lines = ["# Every Actions run, pull request and review", "",
             "Generated by `experiment/collect.py` from the GitHub API and the `autose-runs` branch. Notes come from `results/run_notes.csv`.", "",
             "## Pipeline runs (workflow `autose`)", "",
             "| Run | Started (UTC) | Trigger | Conclusion | Minutes | What happened |", "|---|---|---|---|---|---|"]
    for r in runs:
        if r["name"] != "autose":
            continue
        lines.append("| [%s](%s) | %s | %s | %s | %s | %s |" % (r["id"], r["html_url"], r["created_at"][:16].replace("T", " "), r["event"],
                     r["conclusion"], minutes(r["created_at"], r["updated_at"]), notes.get(str(r["id"]), "")))
    lines += ["", "## Reviewer calibration runs (workflow `review-seeded`)", "", "| Run | Started (UTC) | Conclusion | What happened |", "|---|---|---|---|"]
    for r in runs:
        if r["name"] == "review-seeded":
            lines.append("| [%s](%s) | %s | %s | %s |" % (r["id"], r["html_url"], r["created_at"][:16].replace("T", " "), r["conclusion"], notes.get(str(r["id"]), "")))
    lines += ["", "## Other workflow runs", "", "| Run | Workflow | Started (UTC) | Conclusion | What happened |", "|---|---|---|---|---|"]
    for r in runs:
        if r["name"] not in ("autose", "review-seeded", "ci"):
            lines.append("| [%s](%s) | %s | %s | %s | %s |" % (r["id"], r["html_url"], r["name"], r["created_at"][:16].replace("T", " "), r["conclusion"], notes.get(str(r["id"]), "")))
    ci = [r for r in runs if r["name"] == "ci"]
    lines += ["", "The repository also has %d runs of the `ci` workflow (one per pull request update); they are listed at https://github.com/%s/actions/workflows/ci.yml." % (len(ci), REPO)]
    lines += ["", "## Pull requests", "", "| PR | Branch | State | Title |", "|---|---|---|---|"]
    for p in prs:
        if p["head"]["ref"].startswith(("autose", "seeded")):
            lines.append("| [#%d](%s) | `%s` | %s | %s |" % (p["number"], p["html_url"], p["head"]["ref"], p["state"], p["title"]))
    (RESULTS / "runs.md").write_text("\n".join(lines) + "\n")


# ---- per-run artifacts -----------------------------------------------------------------------------
def artifact_rounds(rb):
    """Yield (key, round, dir) for every runs/issue-*/round-* directory."""
    base = rb / "runs"
    for issue_dir in sorted(base.glob("issue-*")):
        key = issue_dir.name[len("issue-"):]
        for rd in sorted(issue_dir.glob("round-*")):
            yield key, int(rd.name.split("-")[1]), rd


def score(issue_gh, branch, sha, cache, no_score):
    key = "%s@%s" % (branch, sha)
    if key in cache:
        return cache[key]
    if no_score or issue_gh not in HIDDEN_NO:
        return None
    try:
        out = sh([sys.executable, str(ROOT / "experiment" / "score.py"), "--issue", str(HIDDEN_NO[issue_gh]),
                  "--branch", branch, "--sha", sha], cwd=ROOT)
        cache[key] = json.loads(out.strip().splitlines()[-1])
    except Exception as e:                                       # keep going; the row says it was not scored
        cache[key] = {"error": str(e)[:200]}
    return cache[key]


def write_results(rb, runs, notes, no_score):
    cache_f = RESULTS / "score_cache.json"
    cache = read_json(cache_f, {})
    run_by_id = {str(r["id"]): r for r in runs}
    rows, stage_rows = [], []
    for key, rnd, rd in artifact_rounds(rb):
        m = re.match(r"(\d+)(?:-(\w+))?$", key)
        if not m:
            continue
        issue, variant = int(m.group(1)), m.group(2) or "pipeline"
        if issue == 0:
            continue
        meta = read_json(rd / "run.json", {})
        res = read_json(rd / "result.json", {})
        review = read_json(rd / "review.json", {})
        rmeta = read_json(rd / "meta.json", {})
        state = read_json(rd.parent / "state.json", {}).get("rounds", {}).get(str(rnd), {})
        stages = read_lines(rd / "stages.jsonl")
        for s in stages:
            stage_rows.append(dict(s, issue=issue, variant=variant))
        by_run = defaultdict(list)
        for s in stages:
            by_run[s.get("run_id")].append(s)
        # one row per round, using the last run that wrote stage records for it
        last_run = (meta.get("run_id") or (list(by_run)[-1] if by_run else None))
        mine = by_run.get(last_run, []) or stages
        def attempts(n):
            xs = [s for s in mine if str(s["stage"]) == str(n)]
            return len(xs), (1 if xs and any(x["ok"] for x in xs) else 0), (1 if xs and xs[0]["ok"] else 0)
        a = {n: attempts(n) for n in (1, 2, 3, 4)}
        pr_branch = "autose/issue-%d" % issue if variant == "pipeline" else "autose-%s/issue-%d" % (variant, issue)
        sc = score(issue, pr_branch, res["sha"], cache, no_score) if res.get("sha") else None
        run = run_by_id.get(str(last_run), {})
        rows.append({
            "issue": issue, "variant": variant, "round": rnd, "run_id": last_run or "",
            "run_url": run.get("html_url", ""), "started_utc": meta.get("started", ""),
            "released": "yes" if res.get("pr") else "no", "pr": res.get("pr") or "", "head_sha": res.get("sha", ""),
            **{"stage%d_attempts" % n: a[n][0] for n in a}, **{"stage%d_passed" % n: a[n][1] for n in a},
            **{"stage%d_first_try" % n: a[n][2] for n in a},
            "tokens": state.get("tokens", ""), "calls": state.get("calls", ""),
            "status": state.get("status", ""), "stop_reason": (state.get("reason") or "")[:160],
            "hidden_outcome": (sc or {}).get("outcome", "not scored"),
            "hidden_passed": (sc or {}).get("acceptance_passed", ""), "hidden_total": (sc or {}).get("acceptance_total", ""),
            "regressions": (sc or {}).get("regressions", ""),
            "review_verdict": review.get("verdict", "none"), "review_class": review.get("issue_class") or "",
            "review_tier": sorted(set(rmeta.get("tiers", [])))[0] if rmeta.get("tiers") else "",
        })
    cache_f.write_text(json.dumps(cache, indent=1, sort_keys=True))
    cols = list(rows[0].keys()) if rows else []
    with (RESULTS / "results.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        w.writerows(sorted(rows, key=lambda r: (r["variant"], r["issue"], r["round"])))
    return stage_rows


def write_stage_rates(stage_rows):
    agg = defaultdict(lambda: {"attempts": 0, "passed": 0, "runs": set(), "first_try_runs": 0, "first_try_pass": 0})
    seen_first = set()
    for s in stage_rows:
        if not s.get("run_id"):
            continue
        k = (s["variant"], str(s["stage"]))
        a = agg[k]
        a["attempts"] += 1
        a["passed"] += 1 if s["ok"] else 0
        a["runs"].add((s["run_id"], s["issue"], s["round"]))
        first_key = (k, s["run_id"], s["issue"], s["round"])
        if first_key not in seen_first:
            seen_first.add(first_key)
            a["first_try_runs"] += 1
            a["first_try_pass"] += 1 if s["ok"] else 0
    with (RESULTS / "stage_pass_rates.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["variant", "stage", "attempts", "attempts_passed", "attempt_pass_rate", "rounds_reaching_stage", "first_attempt_passed", "first_attempt_pass_rate"])
        for (variant, stage), a in sorted(agg.items()):
            w.writerow([variant, stage, a["attempts"], a["passed"], round(a["passed"] / a["attempts"], 2),
                        a["first_try_runs"], a["first_try_pass"], round(a["first_try_pass"] / a["first_try_runs"], 2)])


# ---- calibration ----------------------------------------------------------------------------------------
def write_seeded(rb):
    labels = {r["pr"]: r for r in csv.DictReader(LABELS.open())}
    rows = []
    for d in sorted((rb / "runs" / "seeded").glob("pr-*/*")):
        pr = d.parent.name.split("-")[1]
        m = re.match(r"(.+)-t(\d+)-run(\d+)$", d.name)
        if not m:
            continue
        variant, trial, run_id = m.groups()
        verdict = (d / "verdict.txt").read_text().strip() if (d / "verdict.txt").exists() else "NONE"
        meta = read_json(d / "meta.json", {})
        label = labels.get(pr, {}).get("label", "")
        if verdict == "NONE":
            outcome = "no valid review"
        elif label == "wrong":
            outcome = "caught" if verdict == "REQUEST_CHANGES" else "missed"
        else:
            outcome = "approved" if verdict == "APPROVE" else "false rejection"
        version = "v3" if int(run_id) >= 44366000000 else ("v2" if int(run_id) >= 44162000000 else "v1")   # v2: JSON formatting step and wrap-up; v3: retry on the next tier (final)
        rows.append({"pr": pr, "label": label, "variant": variant, "reviewer_version": version, "trial": trial, "run_id": run_id, "verdict": verdict,
                     "outcome": outcome, "tier": sorted(set(meta.get("tiers", [])))[0] if meta.get("tiers") else "",
                     "tokens": meta.get("tokens", ""), "problems": "; ".join(meta.get("problems") or [])[:120]})
    with (RESULTS / "seeded.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["pr", "label", "variant", "reviewer_version", "trial", "run_id", "verdict", "outcome", "tier", "tokens", "problems"])
        w.writeheader()
        w.writerows(sorted(rows, key=lambda r: (r["variant"], r["reviewer_version"], r["pr"], r["trial"])))
    return rows


def main():
    a = argparse.ArgumentParser()
    a.add_argument("--no-score", action="store_true")
    args = a.parse_args()
    RESULTS.mkdir(exist_ok=True)
    runs = load_runs()
    prs = json.loads(sh(["gh", "api", "--paginate", "repos/%s/pulls?state=all&per_page=100" % REPO]).replace("][", ","))
    rb = clone_runs_branch()
    seeded = write_seeded(rb)
    notes = load_notes()
    for r in seeded:
        notes.setdefault(r["run_id"], "PR #%s (%s), variant %s, trial %s: %s%s" % (
            r["pr"], r["label"], r["variant"], r["trial"], r["verdict"], " (" + r["outcome"] + ")" if r["outcome"] != r["verdict"] else ""))
    write_runs_md(runs, notes, prs)
    stage_rows = write_results(rb, runs, notes, args.no_score)
    write_stage_rates(stage_rows)
    print("runs:", len(runs), "stage records:", len(stage_rows), "calibration reviews:", len(seeded))


if __name__ == "__main__":
    main()
